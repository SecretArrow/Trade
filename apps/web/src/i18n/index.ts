const DICTS: Record<Locale, Dict> = { en, id };

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let text = DICTS[locale]?.[key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
